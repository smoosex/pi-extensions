import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";
import { getCodexDataDir, getCodexTimeoutMs, getGeneratedImagesRoot } from "../config.ts";
import { GENERATED_IMAGE_MTIME_SLOP_MS, collectGeneratedImageCandidates, detectImageFormat, expandReturnedPath, validateGeneratedImagePath } from "../images.ts";
import { parseCliImageResult } from "../json.ts";
import {
  ERROR_OUTPUT_UPDATE_THROTTLE_MS,
  ProviderExecutionError,
  errorMessageFor,
  looksLikeCliErrorOutput,
  runProcess,
  tailText,
} from "../process.ts";
import type { ImageProvider, ProviderRunInput, ProviderRunResult } from "../types.ts";

const RESULT_SCHEMA = {
  type: "object",
  properties: {
    ok: { type: "boolean" },
    generatedImagePath: { type: "string" },
    message: { type: "string" },
    sessionId: { type: "string" },
  },
  required: ["ok", "generatedImagePath", "message", "sessionId"],
  additionalProperties: false,
};

function parseSessionIdFromOutput(stdout: string, stderr: string): string | undefined {
  const match = `${stderr}\n${stdout}`.match(/session id:\s*([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/i);
  return match?.[1];
}

function buildCodexPrompt(userPrompt: string, imagePaths: string[]): string {
  const lines = [
    "Use the built-in $imagegen skill/tool to generate exactly one raster image.",
    "Do not use the Image API fallback CLI scripts.",
    "Do not copy, move, rename, edit, or delete the generated image file.",
    "After generation, return only JSON matching the provided schema.",
    "Set ok to true if the built-in image_gen call produced an image, either as a filesystem file or as an inline image result in this Codex run.",
    `Set generatedImagePath to the absolute filesystem path only when the generated image file exists under ${getGeneratedImagesRoot()}/<current session id>/.`,
    "If the image was produced only as an inline result and no file exists, set ok to true, generatedImagePath to an empty string, and message to 'inline image result'.",
    "Set message to an empty string on file-path success; otherwise set it to a concise status or failure reason.",
    "Set sessionId to the Codex session id if known; otherwise set it to an empty string.",
    "If image generation fails and no inline image result exists, set ok to false, generatedImagePath to an empty string, and message to the failure reason.",
    "Never return an attached input image path, a clipboard temporary image path, or an image generated by another session.",
  ];

  if (imagePaths.length > 0) {
    lines.push(
      "",
      "Attached images:",
      ...imagePaths.map((imagePath, index) => `Image ${index + 1}: ${imagePath}`),
      "Use the attached images according to the user's prompt. Treat them as references unless the prompt clearly asks to edit or transform them.",
    );
  }

  lines.push("", "Image prompt:", userPrompt);
  return lines.join("\n");
}

async function selectGeneratedImageForSession(sessionId: string, startedAtMs: number, reportedImagePath: string, inputImages: string[]): Promise<string> {
  const sessionDir = join(getGeneratedImagesRoot(), sessionId);
  const normalizedInputImages = new Set(inputImages.map((inputImage) => resolve(inputImage)));
  const candidates = (await collectGeneratedImageCandidates(sessionDir))
    .filter((candidate) => candidate.size > 0)
    .filter((candidate) => candidate.mtimeMs >= startedAtMs - GENERATED_IMAGE_MTIME_SLOP_MS)
    .filter((candidate) => !normalizedInputImages.has(resolve(candidate.path)))
    .sort((a, b) => b.mtimeMs - a.mtimeMs);

  if (candidates.length === 0) {
    throw new Error(`Codex did not create a generated image file for this run under ${sessionDir}. Codex reported: ${reportedImagePath || "<empty>"}`);
  }

  const normalizedReportedPath = reportedImagePath ? resolve(reportedImagePath) : undefined;
  const selected = (normalizedReportedPath && candidates.find((candidate) => resolve(candidate.path) === normalizedReportedPath)) || candidates[0];
  await validateGeneratedImagePath(selected.path, {
    startedAtMs,
    inputImages,
    providerLabel: "Codex",
    requiredRoot: sessionDir,
    requiredRootDescription: `~/.codex/generated_images/${sessionId}`,
  });
  return selected.path;
}

async function findCodexSessionFile(sessionId: string): Promise<string | undefined> {
  const sessionsRoot = join(getCodexDataDir(), "sessions");
  const stack = [sessionsRoot];
  while (stack.length > 0) {
    const dir = stack.pop()!;
    const entries = await readdir(dir, { withFileTypes: true }).catch((error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT" || error.code === "EACCES" || error.code === "EPERM") return [];
      throw error;
    });
    for (const entry of entries) {
      const entryPath = join(dir, entry.name);
      if (entry.isDirectory()) {
        stack.push(entryPath);
      } else if (entry.isFile() && entry.name.endsWith(".jsonl") && entry.name.includes(sessionId)) {
        return entryPath;
      }
    }
  }
  return undefined;
}

function decodeBase64Image(rawValue: string): Buffer | undefined {
  const cleaned = rawValue.trim().replace(/^data:image\/[a-z0-9.+-]+;base64,/i, "");
  if (!cleaned) return undefined;
  const data = Buffer.from(cleaned, "base64");
  return detectImageFormat(data) ? data : undefined;
}

async function extractInlineGeneratedImageForSession(sessionId: string, startedAtMs: number): Promise<string> {
  const sessionFile = await findCodexSessionFile(sessionId);
  if (!sessionFile) throw new Error(`Cannot find Codex rollout for session ${sessionId}.`);

  const minTimestamp = startedAtMs - GENERATED_IMAGE_MTIME_SLOP_MS;
  let selected: { callId: string; data: Buffer; timestampMs: number; extension: string } | undefined;
  const lines = (await readFile(sessionFile, "utf8")).split("\n");
  for (const line of lines) {
    if (!line.trim()) continue;
    let entry: unknown;
    try {
      entry = JSON.parse(line);
    } catch {
      continue;
    }
    const record = entry as { timestamp?: string; type?: string; payload?: { type?: string; call_id?: string; result?: unknown } };
    if (record.type !== "event_msg" || record.payload?.type !== "image_generation_end") continue;
    if (typeof record.payload.result !== "string" || !record.payload.call_id) continue;
    const timestampMs = record.timestamp ? Date.parse(record.timestamp) : 0;
    if (Number.isFinite(timestampMs) && timestampMs > 0 && timestampMs < minTimestamp) continue;
    const data = decodeBase64Image(record.payload.result);
    if (!data) continue;
    const format = detectImageFormat(data);
    if (!format) continue;
    selected = { callId: record.payload.call_id, data, timestampMs, extension: format.extension };
  }

  if (!selected) throw new Error(`Codex did not expose an inline generated image in rollout ${sessionFile}.`);

  const sessionDir = join(getGeneratedImagesRoot(), sessionId);
  await mkdir(sessionDir, { recursive: true });
  const imagePath = join(sessionDir, `${selected.callId}${selected.extension}`);
  await writeFile(imagePath, selected.data);
  return imagePath;
}

async function resolveGeneratedImagePath(sessionId: string, startedAtMs: number, reportedImagePath: string, inputImages: string[]): Promise<string> {
  try {
    return await selectGeneratedImageForSession(sessionId, startedAtMs, reportedImagePath, inputImages);
  } catch (fileError) {
    const imagePath = await extractInlineGeneratedImageForSession(sessionId, startedAtMs).catch((inlineError) => {
      throw new Error(`${errorMessageFor(fileError)} ${errorMessageFor(inlineError)}`);
    });
    await validateGeneratedImagePath(imagePath, {
      startedAtMs,
      inputImages,
      providerLabel: "Codex",
      requiredRoot: join(getGeneratedImagesRoot(), sessionId),
      requiredRootDescription: `~/.codex/generated_images/${sessionId}`,
    });
    return imagePath;
  }
}

export const codexProvider: ImageProvider = {
  id: "codex",
  label: "Codex CLI",
  async run(input: ProviderRunInput): Promise<ProviderRunResult> {
    const tempDir = await mkdtemp(join(tmpdir(), "pi-image-gen-codex-"));
    const schemaPath = join(tempDir, "schema.json");
    const resultPath = join(tempDir, "result.json");
    const timeoutMs = getCodexTimeoutMs();
    const args = [
      "exec",
      "--skip-git-repo-check",
      "--dangerously-bypass-approvals-and-sandbox",
      "--dangerously-bypass-hook-trust",
      "--color",
      "never",
      "--output-schema",
      schemaPath,
      "--output-last-message",
      resultPath,
      "--cd",
      input.cwd,
    ];
    const detailsArgs = () => args.filter((arg) => arg !== schemaPath && arg !== resultPath);
    let stdoutTail = "";
    let stderrTail = "";

    try {
      for (const imagePath of input.imagePaths) {
        args.push("--image", imagePath);
      }
      args.push("-");
      await writeFile(schemaPath, JSON.stringify(RESULT_SCHEMA, null, 2), "utf8");
      let lastErrorUpdateAt = 0;
      let detectedSessionId: string | undefined;
      const publishStatus = (message: string, includeOutput = false) => {
        input.onUpdate?.({
          content: [{ type: "text", text: message }],
          details: {
            provider: "codex",
            command: "codex",
            args: detailsArgs(),
            images: input.imagePaths,
            timeoutMs,
            elapsedMs: Date.now() - input.startedAt,
            stdoutTail: includeOutput && stdoutTail ? tailText(stdoutTail, 2_000) : undefined,
            stderrTail: includeOutput && stderrTail ? tailText(stderrTail, 2_000) : undefined,
          },
        });
      };
      publishStatus("Running codex exec for image generation...");

      const processResult = await runProcess("codex", args, buildCodexPrompt(input.prompt, input.imagePaths), input.cwd, {
        signal: input.signal,
        timeoutMs,
        processLabel: "codex exec",
        env: {
          OPENAI_API_KEY: undefined,
          CODEX_API_KEY: undefined,
        },
        onOutput(stream, chunk, captured) {
          stdoutTail = captured.stdout;
          stderrTail = captured.stderr;
          detectedSessionId ??= parseSessionIdFromOutput(captured.stdout, captured.stderr);
          const now = Date.now();
          if (stream === "stderr" && looksLikeCliErrorOutput(chunk) && now - lastErrorUpdateAt >= ERROR_OUTPUT_UPDATE_THROTTLE_MS) {
            lastErrorUpdateAt = now;
            publishStatus("codex exec reported diagnostic output.", true);
          }
        },
      });
      if (input.signal?.aborted) throw new Error("Codex image generation was aborted.");
      if (processResult.code !== 0) {
        throw new ProviderExecutionError(`codex exec failed with code ${processResult.code ?? "unknown"}.${processResult.stderr ? `\n${processResult.stderr}` : ""}`, {
          stdout: processResult.stdout,
          stderr: processResult.stderr,
          details: { provider: "codex", command: "codex", args: detailsArgs(), timeoutMs, elapsedMs: Date.now() - input.startedAt },
        });
      }

      const resultText = await readFile(resultPath, "utf8").catch(async () => processResult.stdout);
      const cliResult = parseCliImageResult(resultText, "Codex");
      const actualSessionId = detectedSessionId ?? parseSessionIdFromOutput(processResult.stdout, processResult.stderr);
      if (!actualSessionId) {
        throw new Error(
          cliResult.ok
            ? "Codex did not report a session id, so the generated image cannot be safely identified under concurrent runs."
            : cliResult.message || "Codex reported image generation failure.",
        );
      }
      const reportedImagePath = cliResult.generatedImagePath ? expandReturnedPath(cliResult.generatedImagePath, input.cwd) : "";
      const imagePath = await resolveGeneratedImagePath(actualSessionId, input.startedAt, reportedImagePath, input.imagePaths).catch((error) => {
        if (!cliResult.ok) throw new Error(`${cliResult.message || "Codex reported image generation failure."} ${errorMessageFor(error)}`);
        throw error;
      });

      input.onUpdate?.({
        content: [{ type: "text", text: `Codex generated ${basename(imagePath)}.` }],
        details: { provider: "codex", generatedImagePath: imagePath },
      });

      return {
        provider: "codex",
        generatedImagePath: imagePath,
        cliResult: { ...cliResult, ok: true, generatedImagePath: imagePath, message: "", sessionId: actualSessionId },
        inputImages: input.imagePaths,
        stdout: processResult.stdout,
        stderr: processResult.stderr,
        metadata: {
          command: "codex",
          args: detailsArgs(),
          timeoutMs,
          elapsedMs: Date.now() - input.startedAt,
        },
      };
    } catch (error) {
      if (error instanceof ProviderExecutionError) throw error;
      throw new ProviderExecutionError(errorMessageFor(error), {
        stdout: stdoutTail,
        stderr: stderrTail,
        details: { provider: "codex", command: "codex", args: detailsArgs(), timeoutMs, elapsedMs: Date.now() - input.startedAt },
      });
    } finally {
      await rm(tempDir, { recursive: true, force: true });
    }
  },
};
